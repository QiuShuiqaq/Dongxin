param(
    [Parameter(Mandatory = $true)][string]$ArchivePath,
    [ValidatePattern('^[a-zA-Z0-9][a-zA-Z0-9.-]{0,252}$')]
    [string]$ServerAddress = '121.41.198.198',
    [switch]$PrepareOnly
)
$ErrorActionPreference = 'Stop'
$projectDirectory = Split-Path $PSScriptRoot -Parent
$workspaceDirectory = Split-Path $projectDirectory -Parent
$deployKey = Join-Path $workspaceDirectory '.ssh\dongxin_ecs_deploy_20261102'
$knownHosts = Join-Path $workspaceDirectory '.ssh\dongxin_ecs_known_hosts'
$sshExe = Join-Path $env:WINDIR 'System32\OpenSSH\ssh.exe'
$scpExe = Join-Path $env:WINDIR 'System32\OpenSSH\scp.exe'
$tarExe = Join-Path $env:WINDIR 'System32\tar.exe'
$remoteHelper = Join-Path $PSScriptRoot 'prepare-release.sh'
foreach ($requiredPath in @($ArchivePath, $deployKey, $knownHosts, $sshExe, $scpExe, $tarExe, $remoteHelper)) {
    if (-not (Test-Path -LiteralPath $requiredPath -PathType Leaf)) { throw "Required file missing: $requiredPath" }
}
$archive = (Resolve-Path -LiteralPath $ArchivePath).Path
$fileName = [System.IO.Path]::GetFileName($archive)
if ($fileName -notmatch '^dongxin-operations-([A-Za-z0-9][A-Za-z0-9._-]{0,100})\.tgz$') {
    throw 'Use an archive generated by npm run deploy:package.'
}
$version = $Matches[1]
$checksumPath = "$archive.sha256"
if (-not (Test-Path -LiteralPath $checksumPath -PathType Leaf)) { throw "Checksum file missing: $checksumPath" }
$actualHash = (Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant()
$checksum = (Get-Content -LiteralPath $checksumPath -Raw).Trim()
if ($checksum -cne "$actualHash  $fileName") { throw 'Archive SHA256 does not match its checksum file.' }
$manifestText = & $tarExe -xOf $archive './release.json'
if ($LASTEXITCODE -ne 0) { throw 'Cannot read release.json from archive.' }
$manifest = ($manifestText -join "`n") | ConvertFrom-Json
if ($manifest.version -cne $version -or $manifest.nodeMajor -ne 24 -or $manifest.dataFormatVersion -ne 1) {
    throw 'Unsupported release manifest or filename mismatch. Review the migration plan first.'
}
$commonOptions = @(
    '-i', $deployKey, '-o', 'BatchMode=yes', '-o', 'IdentitiesOnly=yes',
    '-o', "UserKnownHostsFile=$knownHosts", '-o', 'StrictHostKeyChecking=yes',
    '-o', 'ConnectTimeout=15', '-o', 'ServerAliveInterval=30', '-o', 'ServerAliveCountMax=3'
)
$destination = "ecs-assist-user@$ServerAddress"
$mode = if ($PrepareOnly) { 'prepare' } else { 'activate' }
$uploadId = [Guid]::NewGuid().ToString('N')
$incoming = "/home/ecs-assist-user/dongxin-incoming/update-$uploadId"
Write-Host "Release: $version; mode: $mode; server: $ServerAddress"
& $sshExe @commonOptions $destination "umask 077 && mkdir -p $incoming"
if ($LASTEXITCODE -ne 0) { throw 'Cannot create upload directory. Check SSH and the security group source IP.' }
& $scpExe @commonOptions $archive $remoteHelper "${destination}:$incoming/"
if ($LASTEXITCODE -ne 0) { throw "Upload failed. Partial files remain at $incoming; the active release has not changed." }
& $sshExe @commonOptions $destination "sudo -n bash $incoming/prepare-release.sh $version $actualHash $mode"
if ($LASTEXITCODE -ne 0) { throw "Release update failed. Inspect the output and $incoming before retrying." }
Write-Host 'Update command completed. Verify login and the required operations pages.'
